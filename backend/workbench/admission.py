#: family -> item -> the version planned to supply it.
PLANNED: Mapping[str, Mapping[str, str]] = {}


def _repo(root: Path, relative: str) -> bool:
    return (root / relative).is_file()


def _live_cases(root: Path) -> set[str]:
    path = root / LIVE_EVAL_CASES
    if not path.is_file():
        return set()
    return {str(case.get("id")) for case in json.loads(path.read_text()) if isinstance(case, dict)}


def assess(
    family: str,
    *,
    root: Path,
    evidence: Mapping[str, Mapping[str, tuple[Any, ...]]] = ADMISSION_EVIDENCE,
    declaration: Any = None,
) -> dict[str, Any]:
    """Which admission items a family has, each verified against the repository."""
    from .contracts.model.family import MODEL_FAMILY_CONTRACTS

    declared = declaration if declaration is not None else declaration_for(family)
    record = evidence.get(family, {})
    items: dict[str, dict[str, Any]] = {}

    traits = getattr(declared, "traits", frozenset())
    items["declaration"] = (
        {"met": True, "detail": sorted(traits)}
        if traits and traits <= TRAIT_VOCABULARY
        else {"met": False, "detail": "no traits declared from the vocabulary"}
    )
    items["envelope"] = (
        {"met": True, "detail": declared.result_shape}
        if declared is not None and getattr(declared, "result_shape", None)
        else {"met": False, "detail": "no result envelope declaration"}
    )
    ledger_class = step_category(FAMILY_OPERATION)
    runs_through = family in MODEL_FAMILY_CONTRACTS or declaration is not None
    items["ledger"] = (
        {"met": True, "detail": f"{FAMILY_OPERATION} -> {ledger_class}"}
        if runs_through and ledger_class != "unclassified"
        else {"met": False, "detail": "the operation that runs it is not classified in the ledger"}
    )
    oracles = [item for item in record.get("oracle", ()) if isinstance(item, Oracle)]
    valid = [
        item for item in oracles
        if item.kind in ORACLE_KINDS and _repo(root, item.fixture) and _repo(root, item.test)
    ]
    items["oracle"] = (
        {"met": True, "detail": [f"{item.kind}: {item.fixture}" for item in valid]}
        if valid else
        {"met": False, "detail": "no R/Stata reference data or parameter-recovery simulation"
                                 + (" (a referenced fixture or test is missing)" if oracles else "")}
    )
    cases = _live_cases(root)
    listed = [case for case in record.get("live_eval", ()) if case in cases]
    items["live_eval"] = (
        {"met": True, "detail": listed}
        if listed else {"met": False, "detail": "no live Agent evaluation case"}
    )
    missing = [item for item in ADMISSION_ITEMS if not items[item]["met"]]
    return {"family": family, "admitted": not missing, "missing": missing, "items": items}


def gap_list(root: Path) -> list[dict[str, Any]]:
    """Every family that is not yet admitted, with what it lacks and when."""
    from .contracts.model.family import MODEL_FAMILY_CONTRACTS

    gaps = []
    for family in sorted(MODEL_FAMILY_CONTRACTS):
        report = assess(family, root=root)
        if report["missing"]:
            gaps.append({
                "family": family,
                "missing": report["missing"],
                "planned": {item: PLANNED.get(family, {}).get(item) for item in report["missing"]},
            })
    return gaps
