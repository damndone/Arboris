"""The admission kit for model families (v1.8.10 design section 3.7).

A family is admitted with five items:

1. declaration -- its traits (and roles, through its family contract);
2. oracle -- R or Stata reference data, or a simulation that recovers known
   parameters within Monte Carlo error;
3. envelope -- its result envelope declaration;
4. ledger -- the operation that runs it is classified in the analysis ledger;
5. live_eval -- at least one live Agent evaluation case.

Applicable checks are derived, not declared (requires <= traits). What each
family has is recorded below as data and verified against the repository: a
referenced oracle fixture, test or evaluation case that does not exist does
not count. Families missing an item are listed with the version planned to
close it; an item missing without a plan fails the tests.

This kit is also the gate a capability generated by the Agent will pass to
become a regular capability (design section 9.1).
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .analysis_ledger import step_category
from .contracts.model.result_envelope_registry import TRAIT_VOCABULARY, declaration_for

ADMISSION_ITEMS = ("declaration", "oracle", "envelope", "ledger", "live_eval")
ORACLE_KINDS = ("r_oracle", "stata_oracle", "simulation_recovery")
LIVE_EVAL_CASES = "scripts/agent_live_eval_cases.json"
#: Model families run through this operation; its ledger class is checked.
FAMILY_OPERATION = "model.genesis"


@dataclass(frozen=True)
class Oracle:
    kind: str
    fixture: str
    test: str


def _r(fixture: str, test: str) -> Oracle:
    return Oracle("r_oracle", fixture, test)


