#!/usr/bin/env python3
"""Write the manual's reference pages from the registries they describe.

What Workbench can do -- its model families, tests, data operations, workflow
steps, Agent tools, ledger categories and export formats -- is declared once in
code. These pages are generated from those declarations so the manual cannot
list a capability that does not exist or miss one that does;
``tests/test_manual_reference.py`` fails when a page is out of date.

    PYTHONPATH=backend .venv/bin/python scripts/generate_manual_reference.py
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

REFERENCE = ROOT / "docs" / "manual" / "reference"
HEADER = "<!-- Generated by scripts/generate_manual_reference.py. Do not edit by hand. -->\n\n"


def _cell(text: object) -> str:
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_cell(value) for value in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


_KIND_TITLES = {
    "model_family": "Model families",
    "statistical_test": "Statistical tests",
    "pack": "Statistical packs",
    "prediction_model": "Prediction models",
    "data_preparation": "Data preparation",
    "data_operation": "Operations",
    "selector": "Selectors",
}


def capabilities_page() -> str:
    from workbench.agent.capability_contract import capability_inventory

    grouped: dict[str, list] = defaultdict(list)
    for capability in capability_inventory():
        grouped[capability.kind].append(capability)
    parts = [
        HEADER,
        "# Capabilities\n\n",
        "Everything Workbench can run, as registered. The Agent reaches the same list: an id "
        "shown here is a name it can use in a proposal or a workflow step.\n\n",
    ]
    for kind in [*_KIND_TITLES, *sorted(set(grouped) - set(_KIND_TITLES))]:
        items = sorted(grouped.get(kind, ()), key=lambda item: item.capability_id)
        if not items:
            continue
        parts.append(f"## {_KIND_TITLES.get(kind, kind)} ({len(items)})\n\n")
        parts.append(_table(["Id", "What it does"], [[f"`{item.capability_id}`", item.summary] for item in items]))
        parts.append("\n")
    return "".join(parts)


def data_operations_page() -> str:
    from workbench.data_operation_registry import data_operation_declarations

    parts = [
        HEADER,
        "# Data operations\n\n",
        "Every data operation creates a new dataset node; the source is never changed. Each one "
        "is confirmed before it runs and recorded in the analysis ledger. In a proposal it is "
        "shown as one sentence, with the parameters one click away.\n\n",
    ]
    for declaration in data_operation_declarations():
        parts.append(f"## `{declaration.workflow_operation_id}`\n\n{declaration.summary}\n\n")
        rows = []
        for name, description in declaration.fields.items():
            if name in declaration.binding_fields:
                continue
            required = "yes" if name in declaration.required else ""
            choices = ", ".join(f"`{value}`" for value in declaration.field_enums.get(name, ()))
            rows.append([f"`{name}`", required, description + (f" One of: {choices}." if choices else "")])
        if rows:
            parts.append(_table(["Field", "Required", "Meaning"], rows))
        parts.append(f"\nExample, as a proposal reads it: *{declaration.sentence(declaration.example)}*\n\n")
    return "".join(parts)


def workflow_steps_page() -> str:
    from workbench.agent.workflow_contracts import workflow_step_vocabulary

    vocabulary = workflow_step_vocabulary()
    parts = [
        HEADER,
        "# Workflow steps\n\n",
        "A workflow (`operation.multi_step`) is a list of steps, each `{step_id, operation_id, "
        "spec, depends_on}`. These are the step operations and their `spec` fields. Steps that "
        "only read data run without a confirmation click (see the Agent chapter).\n\n",
        f"Reported percentiles: {', '.join(str(item) for item in vocabulary['reported_percentiles'])}.\n\n",
    ]
    for operation_id, entry in sorted(vocabulary["step_operations"].items()):
        parts.append(f"## `{operation_id}`\n\n{entry.get('summary', '')}\n\n")
        fields = entry.get("fields") or {}
        if fields:
            required = set(entry.get("required") or ())
            parts.append(
                _table(
                    ["Field", "Required", "Meaning"],
                    [[f"`{name}`", "yes" if name in required else "", text] for name, text in fields.items()],
                )
            )
            parts.append("\n")
    return "".join(parts)


def agent_tools_page() -> str:
    from workbench.egress import CONTENT_CLASSES, LOCAL_DEFAULT_ALLOW, REMOTE_DEFAULT_ALLOW, TOOL_CONTENT_CLASSES

    parts = [
        HEADER,
        "# Agent tools and what they may send\n\n",
        "Every tool the Agent can call, and the class of content its result contains. The "
        "project's data-sharing policy decides, per class, what may be sent to a remote model "
        "provider; anything else stays on this computer and the model receives only a summary.\n\n",
        _table(
            ["Content class", "Sent to a remote provider by default", "Sent to a local model by default"],
            [
                [f"`{name}`", "yes" if name in REMOTE_DEFAULT_ALLOW else "no", "yes" if name in LOCAL_DEFAULT_ALLOW else "no"]
                for name in CONTENT_CLASSES
            ],
        ),
        "\n",
        _table(["Tool", "Content class"], [[f"`{tool}`", f"`{cls}`"] for tool, cls in sorted(TOOL_CONTENT_CLASSES.items())]),
    ]
    return "".join(parts)


def ledger_page() -> str:
    from workbench import analysis_ledger
    from workbench.agent import numeric_grounding, read_only_policy

    parts = [
        HEADER,
        "# Analysis ledger categories\n\n",
        "Every executed step is recorded in `workbench/analysis_ledger.jsonl` under one category. "
        f"Steps in the categories {', '.join(f'`{c}`' for c in sorted(read_only_policy.READ_ONLY_CATEGORIES))} "
        "only read data: an Agent workflow made only of them runs without a confirmation click, "
        f"up to {read_only_policy.MAX_AUTO_STEPS} steps at a time and "
        f"{read_only_policy.SESSION_INFERENTIAL_BUDGET} inferential tests per Agent session. "
        "Everything else waits for the user's confirmation. Categories that change data: "
        f"{', '.join(f'`{c}`' for c in sorted(analysis_ledger.CHANGING_CATEGORIES))}.\n\n",
        "## Exact operation ids\n\n",
        _table(["Operation", "Category"], [[f"`{op}`", f"`{cat}`"] for op, cat in sorted(analysis_ledger._EXACT.items())]),
        "\n## By prefix (first match wins)\n\n",
        _table(["Prefix", "Category"], [[f"`{prefix}*`", f"`{cat}`"] for prefix, cat in analysis_ledger._PREFIXES]),
        "\n## Numeric check\n\n",
        "Before an Agent reply is shown, every decimal number in it, and every whole number from 1,000 up "
        "(years excepted), must match a number the Agent was given, rounded correctly to the digits "
        "written, or a value from the `calculate` tool. "
        f"A failing reply is sent back {numeric_grounding.MAX_REPAIRS} time(s) with the closest real "
        "values; if the rewrite still fails, it is shown with a warning naming the numbers.\n",
    ]
    return "".join(parts)


def export_formats_page() -> str:
    from workbench import tabular_io

    names = {"sav": "SPSS", "zsav": "SPSS, compressed", "dta": "Stata", "csv": "CSV (UTF-8)", "xlsx": "Excel"}
    parts = [
        HEADER,
        "# Export formats\n\n",
        _table(["Format", "Written as"], [[f"`{fmt}`", names.get(fmt, fmt)] for fmt in tabular_io.EXPORT_FORMATS]),
        "\n## Stata releases\n\n",
        _table(
            ["`dta_version`", "Readable by", "Default"],
            [[f"`{version}`", text, "yes" if version == tabular_io.DEFAULT_DTA_VERSION else ""] for version, text in tabular_io.DTA_VERSIONS.items()],
        ),
        "\n## Options\n\n",
        f"- Value labels (`value_label_mode`): {', '.join(f'`{m}`' for m in tabular_io.VALUE_LABEL_MODES)}.\n",
        f"- Declared missing codes (`missing_code_mode`): {', '.join(f'`{m}`' for m in tabular_io.MISSING_CODE_MODES)}.\n",
    ]
    return "".join(parts)


PAGES = {
    "capabilities.md": capabilities_page,
    "data-operations.md": data_operations_page,
    "workflow-steps.md": workflow_steps_page,
    "agent-tools.md": agent_tools_page,
    "analysis-ledger.md": ledger_page,
    "export-formats.md": export_formats_page,
}


def render() -> dict[str, str]:
    return {name: page() for name, page in PAGES.items()}


def main() -> int:
    REFERENCE.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (REFERENCE / name).write_text(text, encoding="utf-8")
        print(f"wrote docs/manual/reference/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
