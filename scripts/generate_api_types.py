#!/usr/bin/env python3
"""Generate the frontend's API types from the backend's OpenAPI (V1812-OPENAPI-TYPES).

The FastAPI app is the single source: its OpenAPI document is rendered by
openapi-typescript into frontend/src/generated/api-schema.ts. ``--check``
regenerates in memory and fails when the committed file differs, so a backend
change that is not regenerated is caught (tests/test_api_types_drift.py).

Usage:
    python3 scripts/generate_api_types.py           # write the file
    python3 scripts/generate_api_types.py --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / "frontend" / "src" / "generated" / "api-schema.ts"
GENERATOR = REPO / "frontend" / "node_modules" / ".bin" / "openapi-typescript"
HEADER = (
    "// Generated by scripts/generate_api_types.py from the backend's OpenAPI.\n"
    "// Do not edit by hand: change the backend, then run the script.\n"
)


def openapi() -> dict:
    sys.path.insert(0, str(REPO / "backend"))
    from workbench.app import app

    return app.openapi()


def render(document: dict) -> str:
    if not GENERATOR.exists():
        raise SystemExit(f"{GENERATOR} is missing; link the shared frontend dependencies")
    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "openapi.json"
        target = Path(directory) / "api-schema.ts"
        source.write_text(json.dumps(document, sort_keys=True), encoding="utf-8")
        subprocess.run(
            [str(GENERATOR), str(source), "--output", str(target), "--alphabetize", "--default-non-nullable=false"],
            check=True, capture_output=True, text=True,
        )
        return HEADER + target.read_text(encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate frontend API types from OpenAPI.")
    parser.add_argument("--check", action="store_true", help="fail when the committed file is out of date")
    args = parser.parse_args(argv)
    text = render(openapi())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(REPO)} is out of date; run python3 scripts/generate_api_types.py", file=sys.stderr)
            return 1
        print("API types are up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
